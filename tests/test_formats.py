from lockfile_reader import Lockfile, LockfileError, parse


def dedent(s: str) -> str:
    return textwrap.dedent(s).lstrip("\n")


def by_id(lf: Lockfile, pid: str) -> Any:
    pkg = lf.get(pid)
    assert pkg is not None, [p.id for p in lf]
    return pkg


